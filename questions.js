window.buildQuestions = function(){
  return QUESTION_TEXTS.map(function(t,i){ return {id:i+1, text:t, type:ANCHOR_KEYS[i%8]}; });
};
window.computeReport = function(scores, top3){
  // scores: {qid(str): 1-6}, top3: [qid(int)]
  var base = {}; ANCHOR_KEYS.forEach(function(k){base[k]=0;});
  buildQuestions().forEach(function(q){
    base[q.type] += parseFloat(scores[String(q.id)]||0);
  });
  top3.forEach(function(qid){
    base[ANCHOR_KEYS[(qid-1)%8]] += 4;
  });
  var avg = {}; ANCHOR_KEYS.forEach(function(k){avg[k]=Math.round(base[k]/5*10)/10;});
  var ranking = ANCHOR_KEYS.slice().sort(function(a,b){return avg[b]-avg[a];});
  var dual = (avg[ranking[0]]-avg[ranking[1]]) <= 0.5;
  var cores = dual ? [ranking[0],ranking[1]] : [ranking[0]];
  var blocks = cores.map(function(k){
    var p = ANCHOR_PROFILES[k];
    return {type:k, tagline:p.tagline, description:p.description, strength:p.strength, advice:p.advice, score:avg[k]};
  });
  return {avg:avg, ranking:ranking, core:ranking[0], dual:dual, cores:cores,
    core_names: dual ? (cores[0]+" + "+cores[1]) : cores[0], blocks:blocks};
};
